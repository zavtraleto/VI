import rowJson from '../../boards/row.json?raw';
import { packRun } from '../app/savedRun';
import { RunTally } from '../app/telemetry';
import { defaultConfig } from '../rules/config';
import { moveOf, solveLevel, tryWay } from '../rules/levelSolver';
import { createRun, step } from '../rules/sim';
import { sameBoard } from './variety';
import { hasReadyGroup } from '../rules/spawn';
import { t } from '../ui/i18n';
import { BOARD_TEXTS } from './boardFiles';
import { buildRow, readRowFile, rowText, touchesRow, type RowFile } from './row';
import { ROW } from './row.gen';

/** The board of B01_s290 under other codes: two 2s a cell apart, cleared by the way round in three moves. */
const lay = (code: string, more: string[] = []): string =>
  [`id: ${code}`, 'status: R', 'faces: 2', ...more, 'par: 3', 'exact: yes', 'way: 0,1,N 0,0,E 1,0,S', '---', ' .   .   .', '24*  .  21', ' .   .   .'].join('\n');
const A = lay('A');
const B = lay('B', ['floor: shut']);
const boards = new Map([['A', A], ['B', B]]);
const file = (more: Partial<RowFile['chapters'][number]> = {}): RowFile => ({
  chapters: [
    { title: 'first', places: [{ board: 'A', role: 'meet', archetype: 'one', help: { plaques: 'all', wait: 'first', sign: 'N', camera: 'hold' } }] },
    { title: 'second', faces: [2, 3], floor: 'open', places: [{ board: 'B', role: 'apply', archetype: 'two' }], ...more },
  ],
});

/** The line a row is refused with, or `built` for a row that is laid. */
function refusal(row: RowFile, files: ReadonlyMap<string, string> = boards): string {
  try {
    buildRow(row, files);
  } catch (error) {
    return (error as Error).message;
  }
  return 'built';
}

describe('buildRow', () => {
  it('numbers the places through the row and keeps what the file says of each', () => {
    const row = buildRow(file(), boards);
    expect(row.places.map((place) => [place.number, place.chapter, place.code])).toEqual([[1, 0, 'A'], [2, 1, 'B']]);
    expect(row.places[0].help).toEqual({ plaques: 'all', wait: 'first', sign: 'N', camera: 'hold' });
    expect(row.places[1].help).toEqual({});
    expect(row.chapters).toEqual([
      { id: 0, title: 'first', faces: null, first: 0, last: 0 },
      { id: 1, title: 'second', faces: [2, 3], first: 1, last: 1 },
    ]);
  });

  it('plays a board of a chapter with faces on them, and with its floor open where the chapter says so', () => {
    const row = buildRow(file(), boards);
    expect(row.places[0].spec.faces).toEqual([2]);
    expect(row.places[1].spec).toMatchObject({ faces: [2, 3], values: [2, 3] });
    expect(row.places[1].spec.floor).toBeUndefined();
    expect(buildRow(file({ floor: undefined }), boards).places[1].spec.floor).toBe(false);
  });

  it('keeps the emotion of a place, and refuses a word that is none of EMOTIONS', () => {
    const one = { chapters: [{ title: 'one', places: [{ board: 'A', role: 'meet', archetype: 'a', emotion: 'gift' }] }] };
    expect(buildRow(one as RowFile, boards).places[0].emotion).toBe('gift');
    const wrong = { chapters: [{ title: 'one', places: [{ board: 'A', role: 'meet', archetype: 'a', emotion: 'joy' }] }] };
    expect(() => buildRow(wrong as RowFile, boards)).toThrow('row: place 1 (A): "emotion: joy" is none of gift, recognition, insight, flow, trick, surprise, tension, payoff, fiero, relief, mastery');
  });

  it('refuses a row it cannot play, in one line that names the place', () => {
    const bad = (change: (row: RowFile) => void): string => {
      const row = file();
      change(row);
      return refusal(row);
    };
    expect(bad((row) => (row.chapters[0].places[0].board = 'Z'))).toBe('row: Z is in the row, and there is no file boards/Z.txt');
    expect(bad((row) => row.chapters[1].places.push({ board: 'A', role: 'rest', archetype: 'again' }))).toBe('row: A is in the row twice (places 1 and 3)');
    expect(refusal(file(), new Map([['A', A.replace('status: R', 'status: D')], ['B', B]]))).toBe('row: A: the file says status D; a board of the row is R');
    expect(bad((row) => (row.chapters[0].places[0].help = { plaques: 'some' as never }))).toBe('row: place 1 (A): "plaques: some" is none of all, near');
    expect(bad((row) => (row.chapters[0].places[0].role = 'lead' as never))).toBe('row: place 1 (A): "role: lead" is none of meet, learn, apply, event, twist, peak, rest');
    expect(bad((row) => ((row.chapters[0].places[0].help as Record<string, unknown>).hlep = 1))).toBe('row: place 1 (A): unknown key "hlep"');
    expect(bad((row) => ((row.chapters[0].places[0] as unknown as Record<string, unknown>).boad = 'A'))).toBe('row: place 1 (A): unknown key "boad"');
  });

  it('reads row.json and prints the module the game reads, the same every time', () => {
    const row = buildRow(readRowFile(JSON.stringify(file())), boards);
    const text = rowText(row);
    expect(text.startsWith('// Generated by node scripts/row.mjs from boards/row.json and boards/*.txt. Do not edit.\n')).toBe(true);
    expect(text).toContain("import type { Row } from './row';");
    expect(text).toContain('export const ROW: Row = {');
    expect(rowText(buildRow(readRowFile(JSON.stringify(file())), boards))).toBe(text);
    expect(() => readRowFile('{ "chapters": 1 }')).toThrow('row: "chapters" is a list of chapters');
  });
});

describe('the live sessions of a row', () => {
  const two = (lives: unknown[]): RowFile => ({ ...file(), lives } as RowFile);

  it('stand after the boards they name, with the codes of their steps', () => {
    const row = buildRow(two([{ after: 'B', step: 2 }, { after: 'A', step: 1, note: 'first' }]), boards);
    expect(row.lives).toEqual([
      { code: 'live-1', step: 1, after: 0 },
      { code: 'live-2', step: 2, after: 1 },
    ]);
    expect(buildRow(file(), boards).lives).toEqual([]);
  });

  it('are refused after a board that is not in the row, on a step twice, on a step that is not a whole number from 1', () => {
    expect(refusal(two([{ after: 'C', step: 1 }]))).toBe('row: live after C: there is no board C in the row');
    expect(refusal(two([{ after: 'A', step: 1 }, { after: 'B', step: 1 }]))).toBe('row: live after B: step 1 is in the row twice');
    expect(refusal(two([{ after: 'A', step: 0 }]))).toBe('row: live after A: "step: 0" is a whole number from 1');
    expect(refusal(two([{ after: 'A', step: 1.5 }]))).toBe('row: live after A: "step: 1.5" is a whole number from 1');
    expect(refusal(two([{ after: 'A', step: 1 }, { after: 'A', step: 2 }]))).toBe('row: live after A: the board has a live session after it already');
    expect(refusal(two([{ after: 'A', step: 1, when: 'now' }]))).toBe('row: live after A: unknown key "when"');
  });
});

describe('touchesRow', () => {
  it('is row.json and the file of a board of the row, and no other file', () => {
    expect(touchesRow('row.json', file())).toBe(true);
    expect(touchesRow('A.txt', file())).toBe(true);
    expect(touchesRow('B.txt', file())).toBe(true);
    expect(touchesRow('C.txt', file())).toBe(false);
    expect(touchesRow('README.md', file())).toBe(false);
  });
});

describe('the row of the game', () => {
  it('is what row.json and the files of the boards lay: run node scripts/row.mjs where it is not', () => {
    expect(rowText(buildRow(readRowFile(rowJson), BOARD_TEXTS))).toBe(rowText(ROW));
  });

  it('has its live sessions after boards of the row, each step once and in order: after places 16, 28, 43, 56, 71 and 85, each the end of its chapter or a rest', () => {
    expect(ROW.lives.map((live) => [live.code, ROW.places[live.after].number])).toEqual([['live-1', 16], ['live-2', 28], ['live-3', 43], ['live-4', 56], ['live-5', 71], ['live-6', 85]]);
    expect(ROW.lives.map((live) => live.step)).toEqual([1, 2, 3, 4, 5, 6]);
    for (const live of ROW.lives) {
      const place = ROW.places[live.after];
      expect(ROW.chapters[place.chapter].last === live.after || place.role === 'rest', live.code).toBe(true);
    }
  });

  it('clears every place by the way its file keeps, in as many moves as it says, and the solver finds none shorter', { timeout: 120_000 }, () => {
    for (const { code, spec } of ROW.places) {
      expect(spec.solution, code).toBeDefined();
      const { state } = tryWay(spec, spec.solution!.map(moveOf));
      expect(state.endReason, code).toBe('passed');
      expect(state.levelRun!.moves, code).toBe(spec.par);
      const solved = solveLevel(spec);
      expect(solved.exhausted, code).toBe(true);
      expect(solved.solution!.par, code).toBe(spec.par);
    }
  });

  it('starts no place with a combo ready to go', () => {
    for (const { code, spec } of ROW.places) {
      const state = createRun({ seed: spec.seed, config: defaultConfig(), level: spec });
      const tops = new Array<number>(spec.size * spec.size).fill(0);
      for (const cube of state.cubes) if (cube.state === 'idle' && (spec.faces ?? []).includes(cube.ori.top)) tops[cube.z * spec.size + cube.x] = cube.ori.top;
      expect(hasReadyGroup(tops, spec.size), code).toBe(false);
    }
  });

  it('names hints that have words', () => {
    for (const { code, help } of ROW.places) if (help.hint) expect(t(help.hint), code).not.toBe(help.hint);
  });

  it('makes on the way of every place only combos of the faces that work', () => {
    for (const { code, spec } of ROW.places) {
      const { values } = tryWay(spec, spec.solution!.map(moveOf));
      expect(values.length, code).toBeGreaterThan(0);
      for (const value of values) expect(spec.faces, code).toContain(value);
    }
  });

  it('has no board twice, and none that is another turned or mirrored', () => {
    const boards = ROW.places.map(({ spec }) => JSON.stringify(spec.layout));
    expect(new Set(boards).size).toBe(boards.length);
    ROW.places.forEach((place, index) => {
      for (const other of ROW.places.slice(index + 1)) expect(sameBoard(place.spec, other.spec), `${place.code} and ${other.code}`).toBe(false);
    });
  });

  it('plays every place with no limit of moves, and keeps none for later when the page goes away', () => {
    for (const { code, spec } of ROW.places) expect(spec.moves, code).toBe(0);
    const { spec } = ROW.places[ROW.places.length - 1];
    const state = createRun({ seed: spec.seed, config: defaultConfig(), level: spec });
    const first = moveOf(spec.solution![0]);
    state.player = { x: first.x, z: first.z, level: 'top' };
    step(state, first.dir);
    for (let i = 0; i < 20; i++) step(state, null);
    expect(state.tick).toBeGreaterThan(0);
    expect(packRun('endless', state, new RunTally())).toBeNull();
  });
});
