/**
 * The letters of the program, drawn dot by dot (the owner, 28 October 2026: «шрифт у тебя
 * хороший вышел, применяй» — after a probe in the manner of EarthBound he asked for). Each sign
 * is as wide as it needs: uprights two dots, crossbars one, corners cut. Capitals are ten dots
 * tall from the fourth row of the sixteen of a line, small letters seven, and what hangs below
 * the line goes to its last row. The figures are all as wide, so numbers stand in columns.
 *
 * Latin, Cyrillic, the figures, the marks the program writes and the letters with marks of the
 * seven languages are here. Anything else - Japanese, arrows - is written in DotGothic16 as before.
 */

export interface Glyph {
  /** The row of the line its first row stands on. */
  top: number;
  /** Rows of dots, `#` lit. */
  rows: readonly string[];
}

/** The first row of a capital, and of a small letter without an ascender. */
const CAP = 3;
const SMALL = 6;
/** Dots between two signs. */
const SPACING = 1;

const GLYPHS = new Map<string, Glyph>();

function cap(signs: string, rows: readonly string[]): void {
  for (const sign of signs) GLYPHS.set(sign, { top: CAP, rows });
}
function small(signs: string, rows: readonly string[], top = SMALL): void {
  for (const sign of signs) GLYPHS.set(sign, { top, rows });
}
function mark(signs: string, top: number, rows: readonly string[]): void {
  for (const sign of signs) GLYPHS.set(sign, { top, rows });
}

