/** The drawn sign, or null for one the program writes in DotGothic16. */
export function glyphOf(sign: string): Glyph | null {
  return GLYPHS.get(sign) ?? null;
}

/** How far a drawn sign moves the line on, in dots; null for a sign that is not drawn here. */
export function glyphAdvance(sign: string): number | null {
  const glyph = GLYPHS.get(sign);
  return glyph ? glyph.rows[0].length + SPACING : null;
}

/** Lights the dots of a drawn sign, its top left at `x, y`, each dot `scale` pixels square. */
export function paintGlyph(ctx: CanvasRenderingContext2D, glyph: Glyph, x: number, y: number, scale: number): void {
  glyph.rows.forEach((row, r) => {
    for (let c = 0; c < row.length; c++) if (row[c] === '#') ctx.fillRect(x + c * scale, y + (glyph.top + r) * scale, scale, scale);
  });
}
