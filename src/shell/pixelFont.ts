/** Marks over and under letters, as rows of dots set over the middle of the letter. */
const ACCENTS: Record<string, readonly string[]> = {
  acute: ['..##', '.##.'],
  grave: ['##..', '.##.'],
  circumflex: ['.##.', '#..#'],
  tilde: ['.#.#', '#.#.'],
  diaeresis: ['##.##'],
  breve: ['#..#', '.##.'],
  dot: ['##'],
};
const CEDILLA = ['.##', '##.'];

/** A letter with a mark over it: two rows over a capital, over a small letter in its own rows. */
function accented(sign: string, base: string, accent: keyof typeof ACCENTS): void {
  const glyph = GLYPHS.get(base)!;
  const over = ACCENTS[accent];
  const width = Math.max(glyph.rows[0].length, over[0].length);
  const centre = (row: string): string => {
    const left = Math.floor((width - row.length) / 2);
    return '.'.repeat(left) + row + '.'.repeat(width - row.length - left);
  };
  const isCap = glyph.top === CAP && base === base.toUpperCase();
  // Over a capital the mark takes the rows above it; over a small letter, the rows over its body.
  const markTop = isCap ? CAP - 3 : SMALL - 3;
  const above = [...over.map(centre), ...Array.from({ length: 3 - over.length }, () => '.'.repeat(width))];
  const body = glyph.rows.map(centre);
  // A small letter with an ascender keeps it: the mark goes over its body, never over its rows.
  if (!isCap && glyph.top < SMALL) {
    GLYPHS.set(sign, { top: glyph.top, rows: body });
    return;
  }
  GLYPHS.set(sign, { top: markTop, rows: [...above, ...body] });
}

/** A letter with the cedilla under it. */
function cedilla(sign: string, base: string): void {
  const glyph = GLYPHS.get(base)!;
  const width = glyph.rows[0].length;
  const left = Math.floor((width - CEDILLA[0].length) / 2);
  const under = CEDILLA.map((row) => '.'.repeat(left) + row + '.'.repeat(width - row.length - left));
  // The line ends on row 12: the cedilla takes the rows under it.
  const end = glyph.top + glyph.rows.length;
  const gap = Array.from({ length: Math.max(0, 13 - end) }, () => '.'.repeat(width));
  GLYPHS.set(sign, { top: glyph.top, rows: [...glyph.rows, ...gap, ...under] });
}

